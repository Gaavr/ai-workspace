# --- вывод и файлы ---

def short(path):
    path = str(path)
    if path.startswith(str(ROOT) + os.sep):
        return path[len(str(ROOT)) + 1:]
    return path.replace(str(HOME), "~", 1)


def act(message):
    print(("[dry-run] " if DRY_RUN else "") + message)


def warn(message):
    print(f"! {message}", file=sys.stderr)


def is_ours(path):
    """Симлинк, который ведёт внутрь репозитория. Только такие скрипт создаёт и удаляет."""
    return path.is_symlink() and os.readlink(path).startswith(str(ROOT) + os.sep)


def link(dest, src):
    if is_ours(dest) and os.readlink(dest) == str(src):
        return
    if (dest.exists() or dest.is_symlink()) and not is_ours(dest):
        warn(f"{short(dest)} уже существует и это не ссылка в репозиторий, пропускаю")
        return
    act(f"link   {short(dest)} -> {short(src)}")
    if DRY_RUN:
        return
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.is_symlink():
        dest.unlink()
    dest.symlink_to(src)


def prune(directory, keep, inside=None):
    """Удаляет из directory наши симлинки, которых нет в keep. С inside — только ведущие в эту папку."""
    if not directory.is_dir() or is_ours(directory):
        return
    for path in sorted(directory.iterdir()):
        if path.name in keep or not is_ours(path):
            continue
        if inside is None or os.readlink(path).startswith(str(inside) + os.sep):
            act(f"unlink {short(path)}")
            if not DRY_RUN:
                path.unlink()


def unlink_dir_link(directory):
    """Каталог целиком был ссылкой в репозиторий. Теперь ссылки ставятся по одной, внутри настоящего каталога."""
    if is_ours(directory):
        act(f"unlink {short(directory)} (ссылки теперь по одной)")
        if not DRY_RUN:
            directory.unlink()


def write_text(path, text, mode=None):
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    act(f"write  {short(path)}")
    if DRY_RUN:
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    if mode is not None:
        tmp.chmod(mode)
    elif path.exists():
        shutil.copymode(path, tmp)
    os.replace(tmp, path)
    return True


def load_env():
    env_file = ROOT / ".env"
    values = {}
    if not env_file.exists():
        return values
    for line in env_file.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip().strip("'\"")
    return values


# --- frontmatter, YAML, TOML ---

def split_frontmatter(text, path):
    match = re.match(r"---\n(.*?)\n---\n?(.*)", text, re.S)
    if not match:
        raise SystemExit(f"{short(path)}: нет frontmatter в начале файла")
    return match.group(1), match.group(2).lstrip("\n")


def scalar(value):
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        return value[1:-1]
    if value in ("true", "false"):
        return value == "true"
    if re.fullmatch(r"-?\d+", value):
        return int(value)
    if re.fullmatch(r"-?\d+\.\d+", value):
        return float(value)
    return value


def parse_meta(raw, path):
    """Плоский frontmatter: ключ: значение. Вложенность записывается через точку в ключе."""
    meta = {}
    for line in raw.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line[0].isspace():
            raise SystemExit(f"{short(path)}: вложенный YAML не поддерживается, пиши ключ через точку: {line.strip()}")
        key, sep, value = line.partition(":")
        if not sep:
            raise SystemExit(f"{short(path)}: не понял строку: {line}")
        meta[key.strip()] = scalar(value.strip())
    return meta


def nest(flat):
    out = {}
    for key, value in flat.items():
        node = out
        *parents, last = key.split(".")
        for part in parents:
            node = node.setdefault(part, {})
        node[last] = value
    return out


def deep_merge(base, extra):
    for key, value in extra.items():
        if isinstance(value, dict) and isinstance(base.get(key), dict):
            deep_merge(base[key], value)
        else:
            base[key] = value
    return base


def yaml_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return json.dumps(value, ensure_ascii=False)


def to_yaml(data, indent=0):
    lines = []
    for key, value in data.items():
        pad = "  " * indent
        if isinstance(value, dict):
            lines.append(f"{pad}{key}:")
            lines.append(to_yaml(value, indent + 1).rstrip("\n"))
        else:
            lines.append(f"{pad}{key}: {yaml_value(value)}")
    return "\n".join(lines) + "\n"


def toml_value(value):
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    # JSON-строки совместимы с базовыми строками TOML.
    return yaml_value(value)


def toml_multiline(text):
    if "'''" not in text:
        return "'''\n" + text + "'''"
    return json.dumps(text, ensure_ascii=False)


# --- скилы и инструкции ---

def collect_skills():
    skills = {}
    for base in SKILL_DIRS:
        if not base.is_dir():
            continue
        for folder in sorted(base.iterdir()):
            skill_file = folder / "SKILL.md"
            if folder.name.startswith(("_", ".")) or not skill_file.is_file():
                continue
            raw, _ = split_frontmatter(skill_file.read_text(encoding="utf-8"), skill_file)
            name = re.search(r"^name:\s*(.+?)\s*$", raw, re.M)
            if not name or scalar(name.group(1)) != folder.name:
                warn(f"{short(skill_file)}: name в шапке должен совпадать с именем папки, пропускаю")
                continue
            if folder.name in skills:
                print(f"  скил {folder.name}: {short(folder)} перекрывает {short(skills[folder.name])}")
            skills[folder.name] = folder
    return skills


def sync_skills():
    skills = collect_skills()
    for directory in SKILL_LINKS:
        unlink_dir_link(directory)
        for name, folder in skills.items():
            link(directory / name, folder)
        prune(directory, skills)
    for directory in LEGACY_LINK_DIRS:
        prune(directory, set())
    print(f"скилы: {', '.join(skills) or 'нет'}")


def sync_instructions():
    for dest in INSTRUCTION_LINKS:
        link(dest, INSTRUCTIONS)


# --- агенты ---

def load_agents():
    agents = {}
    for base in AGENT_DIRS:
        if not base.is_dir():
            continue
        for path in sorted(base.glob("*.md")):
            if path.name.startswith(("_", ".")) or path.name == "README.md":
                continue
            raw, body = split_frontmatter(path.read_text(encoding="utf-8"), path)
            meta = parse_meta(raw, path)
            meta.setdefault("name", path.stem)
            if "description" not in meta:
                raise SystemExit(f"{short(path)}: нет поля description")
            agents[meta["name"]] = (meta, body)
    return agents


def tool_overrides(meta, tool):
    prefix = tool + "."
    return {key[len(prefix):]: value for key, value in meta.items() if key.startswith(prefix)}


def tier_fields(meta, tool, targets):
    tier = meta.get("tier")
    if not tier:
        return {}
    if not any(tier in fields for name, fields in targets.items() if not name.startswith("_")):
        raise SystemExit(f"агент {meta['name']}: уровня {tier} нет в agents/targets.json")
    return dict(targets.get(tool, {}).get(tier, {}))


def render_claude(meta, body, targets):
    front = {"name": meta["name"], "description": meta["description"]}
    front.update(tier_fields(meta, "claude", targets))
    if meta.get("access") == "read-only":
        front["disallowedTools"] = "Write, Edit, NotebookEdit"
    deep_merge(front, nest(tool_overrides(meta, "claude")))
    return "---\n" + to_yaml(front) + "---\n" + body


def render_opencode(meta, body, targets):
    front = {"description": meta["description"], "mode": meta.get("role", "subagent")}
    front.update(tier_fields(meta, "opencode", targets))
    if "temperature" in meta:
        front["temperature"] = meta["temperature"]
    if meta.get("access") == "read-only":
        front["permission"] = {"edit": "deny"}
    deep_merge(front, nest(tool_overrides(meta, "opencode")))
    return "---\n" + to_yaml(front) + "---\n" + body


def render_codex(meta, body, targets):
    # sandbox_mode в файле агента Codex игнорирует, поэтому запрет правок только словами.
    instructions = (READ_ONLY_NOTE + "\n\n" + body) if meta.get("access") == "read-only" else body
    fields = {"name": meta["name"], "description": meta["description"]}
    fields.update(tier_fields(meta, "codex", targets))
    fields.update(tool_overrides(meta, "codex"))  # TOML понимает ключи через точку как есть
    lines = [f"{key} = {toml_value(value)}" for key, value in fields.items()]
    lines.append("developer_instructions = " + toml_multiline(instructions))
    return "\n".join(lines) + "\n"


RENDERERS = {
    "claude": (render_claude, ".md"),
    "opencode": (render_opencode, ".md"),
    "codex": (render_codex, ".toml"),
}


def publish(out_dir, files, directory, inside=None):
    """Пишет files в out_dir и ставит на них ссылки в directory. Лишнее из обоих мест убирает."""
    if out_dir.is_dir() and not DRY_RUN:
        for stale in out_dir.iterdir():
            if stale.name not in files:
                stale.unlink()
    for filename, text in files.items():
        write_text(out_dir / filename, text)

    unlink_dir_link(directory)
    for filename in files:
        link(directory / filename, out_dir / filename)
    prune(directory, files, inside)


def sync_agents(personas):
    targets = json.loads(TARGETS.read_text(encoding="utf-8"))
    agents = load_agents()
    for name, (meta, body) in personas.items():
        if name in agents:
            raise SystemExit(f"персона {name}: агент с таким именем уже есть")
        agents[name] = (persona_agent(meta), body)

    for tool, (render, ext) in RENDERERS.items():
        files = {}
        for name, (meta, body) in agents.items():
            # Основной агент выбирается только в OpenCode. В остальных он стал бы подагентом.
            if meta.get("role") == "primary" and tool != "opencode":
                continue
            files[name + ext] = render(meta, body, targets)
        publish(BUILD / tool / "agents", files, AGENT_LINKS[tool])
        print(f"агенты {tool}: {', '.join(n.rsplit('.', 1)[0] for n in files) or 'нет'}")


# --- персоны ---

def load_personas():
    """Персоны Open WebUI из prompts/. Для инструментов кода это режим разговора, а не подагент."""
    personas = {}
    for base in PERSONA_DIRS:
        if not base.is_dir():
            continue
        for path in sorted(base.glob("*.md")):
            if path.name.startswith(("_", ".")) or path.name == "README.md":
                continue
            raw, body = split_frontmatter(path.read_text(encoding="utf-8"), path)
            meta = parse_meta(raw, path)
            for required in ("id", "name"):
                if required not in meta:
                    raise SystemExit(f"{short(path)}: нет поля {required}")
            if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", str(meta["id"])):
                raise SystemExit(f"{short(path)}: id только из латиницы в нижнем регистре, цифр и дефиса")
            meta.setdefault("description", meta["name"])
            personas[meta["id"]] = (meta, body)
    return personas


def persona_agent(meta):
    """Персона как основной агент. base — алиас LiteLLM для Open WebUI, инструментам он не нужен."""
    agent = {key: value for key, value in meta.items() if key not in ("id", "name", "base")}
    agent.update(name=meta["id"], role="primary")
    return agent


def render_claude_style(meta, body):
    # Без инструкций для кода Claude Code остаётся собеседником в роли персоны, инструменты при этом не теряет.
    front = {"name": meta["name"], "description": meta["description"], "keep-coding-instructions": False}
    deep_merge(front, nest(tool_overrides(meta, "claude")))
    return "---\n" + to_yaml(front) + "---\n" + body


def render_codex_profile(meta, body, targets):
    fields = tier_fields(persona_agent(meta), "codex", targets)
    fields.update(tool_overrides(meta, "codex"))
    lines = [f"# Персона «{meta['name']}», запуск: codex -p {meta['id']}", "# Собрано scripts/sync-agents.py из prompts/, не править."]
    lines += [f"{key} = {toml_value(value)}" for key, value in fields.items()]
    lines.append("developer_instructions = " + toml_multiline(body))
    return "\n".join(lines) + "\n"


def render_codex_tier(tier, alias, model):
    lines = [
        f"# Уровень «{tier}» через шлюз, запуск: codex -p {tier}",
        "# Собрано scripts/sync-agents.py из agents/targets.json и litellm/config.yaml, не править.",
        'model_provider = "gateway"',
        f"model = {toml_value(alias)}",
    ]
    if "context" in model.get("limit", {}):
        lines.append(f"model_context_window = {model['limit']['context']}")
    return "\n".join(lines) + "\n"


def codex_tier_profiles(targets, env):
    """Профили Codex на уровни OpenCode, чья модель — алиас шлюза: codex -p smart."""
    models = gateway_models(env, quiet=True)
    profiles = {}
    for tier, fields in targets.get("opencode", {}).items():
        model = fields.get("model", "")
        if not model.startswith("gateway/"):
            continue
        alias = model.removeprefix("gateway/")
        if alias not in models:
            warn(f"профиль Codex {tier}: алиаса {alias} нет в шлюзе, пропускаю")
            continue
        profiles[tier] = render_codex_tier(tier, alias, models[alias])
    return profiles


def sync_personas(personas, env):
    targets = json.loads(TARGETS.read_text(encoding="utf-8"))
    styles = {pid + ".md": render_claude_style(meta, body) for pid, (meta, body) in personas.items()}
    publish(BUILD / "claude" / "output-styles", styles, PERSONA_LINKS["claude"])

    # В ~/.codex лежат и чужие профили, и наша ссылка на AGENTS.md: чистим только ссылки на свои профили.
    out_dir = BUILD / "codex" / "profiles"
    profiles = {pid + ".config.toml": render_codex_profile(meta, body, targets) for pid, (meta, body) in personas.items()}
    tiers = codex_tier_profiles(targets, env)
    for tier, text in tiers.items():
        if tier in personas:
            raise SystemExit(f"профиль Codex {tier}: персона с таким id уже есть")
        profiles[tier + ".config.toml"] = text
    publish(out_dir, profiles, PERSONA_LINKS["codex"], inside=out_dir)
    print(f"персоны: {', '.join(personas) or 'нет'}")
    print(f"профили Codex на шлюз: {', '.join(tiers) or 'нет'}")


# --- MCP ---

def server_vars(server):
    texts = list(server.get("args", [])) + list(server.get("env", {}).values()) + [server.get("url", "")]
    texts += list(server.get("headers", {}).values())
    return sorted({name for text in texts for name in VAR.findall(text)})


def active_servers(env):
    servers = json.loads(MCP_SERVERS.read_text(encoding="utf-8")).get("mcpServers", {})
    active = {}
    for name, server in servers.items():
        if server.get("disabled"):
            continue
        if "url" in server and server_vars(server):
            raise SystemExit(f"mcp {name}: ${{VAR}} поддерживается только у серверов с command")
        missing = [var for var in server_vars(server) if not (os.environ.get(var) or env.get(var))]
        if missing:
            print(f"  mcp {name}: пропущен, в .env пусто: {', '.join(missing)}")
            continue
        active[name] = server
    return active


def client_entry(name, server, tool):
    """Запись для клиента. Секретов в ней нет: stdio-серверы запускаются через mcp-run.py."""
    if "url" in server:
        return {
            "claude": {"type": "http", "url": server["url"]},
            "opencode": {"type": "remote", "url": server["url"]},
            "codex": {"url": server["url"]},
        }[tool]
    return {
        "claude": {"type": "stdio", "command": str(MCP_RUN), "args": [name]},
        "opencode": {"type": "local", "command": [str(MCP_RUN), name]},
        "codex": {"command": str(MCP_RUN), "args": [name]},
    }[tool]


def load_state():
    if MCP_STATE.exists():
        return json.loads(MCP_STATE.read_text(encoding="utf-8"))
    return {}


def sync_claude_mcp(active, state):
    data = json.loads(CLAUDE_JSON.read_text(encoding="utf-8")) if CLAUDE_JSON.exists() else {}
    servers = data.setdefault("mcpServers", {})
    before = json.dumps(servers, sort_keys=True)
    managed = set(state.get("claude", []))
    for name in managed - set(active):
        servers.pop(name, None)
    written = []
    for name, server in active.items():
        entry = client_entry(name, server, "claude")
        if name in servers and name not in managed and servers[name] != entry:
            warn(f"~/.claude.json: сервер {name} уже настроен вручную, пропускаю")
            continue
        servers[name] = entry
        written.append(name)
    if json.dumps(servers, sort_keys=True) != before:
        # Файл живой, Claude Code пишет в него сам: читаем и сразу заменяем атомарно.
        write_text(CLAUDE_JSON, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    return written


def sync_codex_config(active):
    """Свой блок в ~/.codex/config.toml: провайдер шлюза и MCP-серверы."""
    text = CODEX_TOML.read_text(encoding="utf-8") if CODEX_TOML.exists() else ""
    text = re.sub(
        r"\n*" + re.escape(CODEX_BEGIN) + r".*?" + re.escape(CODEX_END) + r"\n?", "\n", text, flags=re.S
    ).rstrip("\n") + "\n"
    blocks = []
    if re.search(r"^\[model_providers\.gateway\]", text, re.M):
        warn("~/.codex/config.toml: провайдер gateway уже настроен вручную, пропускаю")
    else:
        # Codex 0.167 принимает только Responses API, LiteLLM переводит его в chat сам.
        # Ключ — заглушка шлюза на 127.0.0.1, не секрет.
        blocks.append("\n".join([
            "[model_providers.gateway]",
            'name = "LiteLLM (ai-workspace)"',
            f"base_url = {toml_value(GATEWAY_URL)}",
            'wire_api = "responses"',
            f'http_headers = {{ Authorization = {toml_value("Bearer " + GATEWAY_KEY)} }}',
        ]))
    for name, server in active.items():
        if re.search(r"^\[mcp_servers\." + re.escape(name) + r"\]", text, re.M):
            warn(f"~/.codex/config.toml: сервер {name} уже настроен вручную, пропускаю")
            continue
        lines = [f"[mcp_servers.{name}]"]
        lines += [f"{key} = {toml_value(value)}" for key, value in client_entry(name, server, "codex").items()]
        blocks.append("\n".join(lines))
    if blocks:
        text += "\n" + CODEX_BEGIN + "\n" + "\n\n".join(blocks) + "\n" + CODEX_END + "\n"
    write_text(CODEX_TOML, text)


def gateway_models(env, quiet=False):
    """Алиасы из litellm/config.yaml. PyYAML не нужен: берём model_name и лимиты из model_info.

    Алиас с пустым ключом (api_key: os.environ/VAR) пропускается — то же правило,
    что у scripts/gateway-config.py, на котором стартует шлюз.
    """
    lines = [line for line in LITELLM_CONFIG.read_text(encoding="utf-8").splitlines() if not line.lstrip().startswith("#")]
    text = "\n".join(lines)
    section = re.search(r"^model_list:\n(.*?)(?=^\S|\Z)", text, re.M | re.S)
    models = {}
    for block in re.split(r"^\s*- model_name:", section.group(1) if section else "", flags=re.M)[1:]:
        name = block.split("\n", 1)[0].strip()
        key = re.search(r"^\s*api_key:\s*os\.environ/(\w+)", block, re.M)
        if key and not (os.environ.get(key.group(1)) or env.get(key.group(1))):
            if not quiet:
                print(f"  gateway/{name}: выключен, в .env пусто: {key.group(1)}")
            continue
        model = {"name": name, "tool_call": True}
        limit = {}
        for key, field in (("max_input_tokens", "context"), ("max_output_tokens", "output")):
            found = re.search(rf"^\s*{key}:\s*(\d+)", block, re.M)
            if found:
                limit[field] = int(found.group(1))
        if limit:
            model["limit"] = limit
        models[name] = model
    return models


def sync_opencode_config(active, targets, env):
    # Глобальные opencode.json и opencode.jsonc OpenCode сливает: здесь шлюз и MCP, в .jsonc — личные правки.
    models = gateway_models(env)
    config = {
        "$schema": "https://opencode.ai/config.json",
        "provider": {
            "gateway": {
                "npm": "@ai-sdk/openai-compatible",
                "name": "LiteLLM",
                "options": {"baseURL": GATEWAY_URL, "apiKey": GATEWAY_KEY},
                "models": models,
            }
        },
    }
    default = targets.get("opencode", {}).get("smart", {}).get("model")
    if default:
        config["model"] = default
    for tier, fields in targets.get("opencode", {}).items():
        alias = fields.get("model", "").removeprefix("gateway/")
        if fields.get("model", "").startswith("gateway/") and alias not in models:
            warn(f"agents/targets.json: opencode.{tier} ссылается на {alias}, его нет в litellm/config.yaml")
    if active:
        config["mcp"] = {name: client_entry(name, server, "opencode") for name, server in active.items()}
    out = BUILD / "opencode" / "opencode.json"
    write_text(out, json.dumps(config, indent=2, ensure_ascii=False) + "\n")
    link(OPENCODE_JSON, out)


def sync_mcpo(active, env):
    """Open WebUI ходит в MCP через mcpo в контейнере, обёртка с хоста там недоступна: значения подставляются сразу."""

    def expand(text):
        return VAR.sub(lambda m: os.environ.get(m.group(1)) or env.get(m.group(1), ""), text)

    servers = {}
    for name, server in active.items():
        if "url" in server:
            servers[name] = {"type": "streamable-http", "url": server["url"]}
            continue
        servers[name] = {
            "command": server["command"],
            "args": [expand(a) for a in server.get("args", [])],
            "env": {key: expand(value) for key, value in server.get("env", {}).items()},
        }
    write_text(MCPO_JSON, json.dumps({"mcpServers": servers}, indent=2, ensure_ascii=False) + "\n", mode=0o600)


